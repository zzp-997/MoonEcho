class GLMChatService:
    """智谱 GLM-4 对话服务。

    提供真实的智谱 GLM-4 API 调用，支持：
    - 同步对话（chat）
    - 流式输出（chat_stream）
    - 三种性格差异化（小温/老黑/阿理）
    - 重试机制和超时处理
    - 对话历史管理
    """

    # 有效的性格标识
    VALID_PERSONALITIES = ("xiaowen", "laohei", "ali")

    def __init__(
        self,
        api_key: str = "",
        model: str = "glm-4-flash",
        base_url: str = "https://open.bigmodel.cn/api/paas/v4",
        personality: str = "xiaowen",
        timeout: float = 30.0,
        max_retries: int = 3,
    ) -> None:
        """初始化智谱 GLM-4 对话服务。

        Args:
            api_key: 智谱 API Key，为空时将无法调用 API
            model: 模型名称，可选 glm-4-flash / glm-4-plus
            base_url: API 基础 URL
            personality: 性格类型，可选 xiaowen / laohei / ali
            timeout: 请求超时时间（秒）
            max_retries: 最大重试次数

        Raises:
            ValueError: 当 personality 不在有效列表中时
        """
        # 延迟导入以避免循环依赖
        from .ai_config import (
            ERROR_MESSAGES,
            RetryConfig,
            get_system_prompt,
            get_greeting,
        )

        if personality not in self.VALID_PERSONALITIES:
            available = ", ".join(self.VALID_PERSONALITIES)
            raise ValueError(f"未知的性格类型: {personality}，可用选项: [{available}]")

        self._api_key = api_key
        self._model = model
        self._base_url = base_url.rstrip("/")
        self._personality = personality
        self._timeout = timeout
        self._max_retries = max_retries
        self._retry_config = RetryConfig(
            max_retries=max_retries,
            timeout=timeout,
        )

        # 获取 System Prompt
        self._system_prompt = get_system_prompt(personality)
        self._greeting = get_greeting(personality)

        # 标记 API Key 是否可用
        self._api_available = bool(api_key)

        if not self._api_available:
            logger.warning(
                "[GLMChat] API Key 未配置，服务将返回错误提示。"
                "请在环境变量中设置 ZHIPU_API_KEY"
            )
        else:
            logger.info(
                "[GLMChat] 初始化完成，模型: %s，性格: %s",
                model,
                personality
            )

    @property
    def personality(self) -> str:
        """获取当前性格标识。"""
        return self._personality

    def get_greeting(self) -> str:
        """获取当前性格的开场白。"""
        return self._greeting

    def _prepare_messages(
        self,
        prompt: str,
        context: dict[str, Any] | None = None,
    ) -> list[dict[str, str]]:
        """准备 API 请求的 messages 参数。

        Args:
            prompt: 用户输入内容
            context: 可选的上下文信息，包含对话历史等

        Returns:
            messages 列表
        """
        messages = [
            {"role": "system", "content": self._system_prompt}
        ]

        # 如果有对话历史，添加到 messages 中
        if context and "history" in context:
            history = context["history"]
            if isinstance(history, list):
                for msg in history:
                    role = msg.get("role")
                    content = msg.get("content")
                    if role in ("user", "assistant") and content:
                        messages.append({"role": role, "content": content})

        # 添加当前用户输入
        messages.append({"role": "user", "content": prompt})

        return messages

    def _build_request_params(
        self,
        messages: list[dict[str, str]],
        stream: bool = False,
    ) -> tuple[str, dict[str, str], dict[str, Any]]:
        """构建 API 请求参数。

        Args:
            messages: 对话消息列表
            stream: 是否使用流式输出

        Returns:
            (url, headers, payload) 元组
        """
        url = f"{self._base_url}/chat/completions"
        headers = {
            "Authorization": f"Bearer {self._api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self._model,
            "messages": messages,
            "stream": stream,
        }
        return url, headers, payload

    async def _call_api(
        self,
        messages: list[dict[str, str]],
    ) -> tuple[dict[str, Any] | None, str | None]:
        """调用智谱 API（非流式）。

        Args:
            messages: 对话消息列表

        Returns:
            (响应数据, 错误信息)：成功时返回 (data, None)，失败时返回 (None, error)

        Note:
            此方法包含重试逻辑，会自动重试失败的请求。
        """
        import httpx

        if not self._api_available:
            return None, "API Key 未配置"

        url, headers, payload = self._build_request_params(messages, stream=False)

        last_error = None
        for attempt in range(self._max_retries):
            try:
                async with httpx.AsyncClient(timeout=self._timeout) as client:
                    response = await client.post(
                        url,
                        headers=headers,
                        json=payload,
                    )
                    response.raise_for_status()
                    data = response.json()
                    return data, None

            except httpx.TimeoutException:
                last_error = f"请求超时（{self._timeout}秒）"
                logger.warning(
                    "[GLMChat] 请求超时（第%d次）",
                    attempt + 1
                )
            except httpx.HTTPStatusError as e:
                last_error = f"HTTP 错误: {e.response.status_code}"
                logger.warning(
                    "[GLMChat] HTTP 错误（第%d次）: %s",
                    attempt + 1,
                    last_error
                )
            except Exception as e:
                last_error = f"未知错误: {str(e)}"
                logger.error(
                    "[GLMChat] 未知错误（第%d次）: %s",
                    attempt + 1,
                    last_error
                )

            # 重试前等待
            if attempt < self._max_retries - 1:
                delay = self._retry_config.get_delay(attempt)
                logger.info("[GLMChat] 等待 %.1f 秒后重试...", delay)
                await asyncio.sleep(delay)

        return None, last_error or "未知错误"

    async def chat(
        self,
        prompt: str,
        context: dict[str, Any] | None = None,
    ) -> str:
        """同步对话，返回 AI 文本回复。

        Args:
            prompt: 用户输入内容
            context: 可选的上下文信息，支持：
                - history: 对话历史列表，格式为 [{"role": "user/assistant", "content": "..."}]

        Returns:
            AI 的文本回复

        Note:
            如果 API Key 未配置或调用失败，将返回错误提示信息而非抛出异常。
        """
        if not self._api_available:
            return "抱歉，AI 服务暂时不可用。请稍后重试或联系客服。"

        messages = self._prepare_messages(prompt, context)
        logger.info(
            "[GLMChat] 发送请求，模型: %s，性格: %s，消息数: %d",
            self._model,
            self._personality,
            len(messages)
        )

        data, error = await self._call_api(messages, stream=False)

        if error:
            logger.error("[GLMChat] API 调用失败: %s", error)
            return "抱歉，AI 服务暂时出现问题，请稍后重试。"

        if not data:
            return "抱歉，AI 服务返回数据异常，请稍后重试。"

        try:
            content = data["choices"][0]["message"]["content"]
            logger.info(
                "[GLMChat] 收到回复，长度: %d 字符",
                len(content)
            )
            return content
        except (KeyError, IndexError) as e:
            logger.error("[GLMChat] 解析响应失败: %s, 数据: %s", e, data)
            return "抱歉，AI 服务返回数据异常，请稍后重试。"

    async def chat_stream(
        self,
        prompt: str,
        context: dict[str, Any] | None = None,
    ) -> AsyncGenerator[str, None]:
        """流式对话，逐步返回 SSE 格式的 AI 文本片段。

        输出格式：
            data: {"content": "xxx", "done": false}\\n\\n
            最后一个 chunk:
            data: {"content": "", "done": true}\\n\\n

        Args:
            prompt: 用户输入内容
            context: 可选的上下文信息

        Yields:
            SSE 格式的文本片段
        """
        import httpx

        if not self._api_available:
            error_msg = "抱歉，AI 服务暂时不可用。请稍后重试或联系客服。"
            sse_data = json.dumps({"content": error_msg, "done": True}, ensure_ascii=False)
            yield f"data: {sse_data}\n\n"
            return

        messages = self._prepare_messages(prompt, context)
        url, headers, payload = self._build_request_params(messages, stream=True)
        logger.info(
            "[GLMChat] 发送流式请求，模型: %s，性格: %s，消息数: %d",
            self._model,
            self._personality,
            len(messages)
        )

        # 带重试的流式请求
        last_error = None
        for attempt in range(self._max_retries):
            try:
                async with httpx.AsyncClient(timeout=self._timeout) as client:
                    async with client.stream(
                        "POST",
                        url,
                        headers=headers,
                        json=payload,
                    ) as response:
                        if response.status_code != 200:
                            error_text = await response.aread()
                            last_error = f"API 错误 ({response.status_code}): {error_text.decode()}"
                            logger.warning(
                                "[GLMChat] 流式 API 请求失败（第%d次）: %s",
                                attempt + 1,
                                last_error
                            )
                            # 重试
                            if attempt < self._max_retries - 1:
                                delay = self._retry_config.get_delay(attempt)
                                logger.info("[GLMChat] 等待 %.1f 秒后重试...", delay)
                                await asyncio.sleep(delay)
                            continue

                        # 解析 SSE 流
                        full_content = []
                        async for line in response.aiter_lines():
                            if not line:
                                continue

                            # SSE 格式：data: {...}
                            if line.startswith("data: "):
                                data_str = line[6:]  # 去掉 "data: " 前缀

                                # 检查是否为结束标记
                                if data_str.strip() == "[DONE]":
                                    end_data = json.dumps({"content": "", "done": True}, ensure_ascii=False)
                                    yield f"data: {end_data}\n\n"
                                    logger.info(
                                        "[GLMChat] 流式输出结束，总长度: %d 字符",
                                        len("".join(full_content))
                                    )
                                    return

                                # 解析 JSON 数据
                                try:
                                    chunk_data = json.loads(data_str)
                                    # 智谱 API 格式：choices[0].delta.content
                                    delta = chunk_data.get("choices", [{}])[0].get("delta", {})
                                    content = delta.get("content", "")

                                    if content:
                                        full_content.append(content)
                                        sse_data = json.dumps(
                                            {"content": content, "done": False},
                                            ensure_ascii=False
                                        )
                                        yield f"data: {sse_data}\n\n"
                                except json.JSONDecodeError as e:
                                    logger.warning("[GLMChat] 解析 SSE 数据失败: %s, 数据: %s", e, data_str)
                                    continue

                        # 流正常结束但未收到 [DONE] 标记
                        if full_content:
                            end_data = json.dumps({"content": "", "done": True}, ensure_ascii=False)
                            yield f"data: {end_data}\n\n"
                            logger.info(
                                "[GLMChat] 流式输出结束（无 [DONE] 标记），总长度: %d 字符",
                                len("".join(full_content))
                            )
                        return  # 成功完成，退出重试循环

            except httpx.TimeoutException:
                last_error = f"请求超时（{self._timeout}秒）"
                logger.warning("[GLMChat] 流式请求超时（第%d次）", attempt + 1)
            except httpx.HTTPStatusError as e:
                last_error = f"HTTP 错误: {e.response.status_code}"
                logger.warning("[GLMChat] 流式 HTTP 错误（第%d次）: %s", attempt + 1, last_error)
            except Exception as e:
                last_error = f"未知错误: {str(e)}"
                logger.error("[GLMChat] 流式未知错误（第%d次）: %s", attempt + 1, last_error)

            # 重试前等待
            if attempt < self._max_retries - 1:
                delay = self._retry_config.get_delay(attempt)
                logger.info("[GLMChat] 等待 %.1f 秒后重试...", delay)
                await asyncio.sleep(delay)

        # 所有重试均失败
        logger.error("[GLMChat] 流式 API 调用最终失败: %s", last_error)
        error_msg = "抱歉，AI 服务暂时出现问题，请稍后重试。"
        sse_data = json.dumps({"content": error_msg, "done": True}, ensure_ascii=False)
        yield f"data: {sse_data}\n\n"


