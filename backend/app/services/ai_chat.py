AI_CHAT_SERVICES: dict[str, type[MockAIChat | GLMChatService]] = {
    "mock": MockAIChat,
    "glm_free": GLMChatService,
    "glm": GLMChatService,
}


def create_ai_chat_service(
    provider: str = "mock",
    api_key: str = "",
    **kwargs: Any,
) -> MockAIChat | GLMChatService:
    """根据配置创建 AI 对话服务实例。

    Args:
        provider: 服务提供者名称，可选 mock / glm_free / glm
        api_key: API Key（仅 GLM 服务需要）
        **kwargs: 传递给 AI 服务构造函数的额外参数
            personality: 性格类型，可选 xiaowen / laohei / ali
            model: 模型名称（仅 GLM 有效），可选 glm-4-flash / glm-4-plus
            timeout: 请求超时时间（仅 GLM 有效），默认 30 秒
            max_retries: 最大重试次数（仅 GLM 有效），默认 3 次

    Returns:
        AI 对话服务实例

    Raises:
        ValueError: 当 provider 名称不在可用列表中时

    Note:
        - mock 服务不需要 api_key
        - glm_free 和 glm 服务需要有效的 api_key
        - 如果 api_key 未配置，GLM 服务会优雅降级（返回错误信息而非崩溃）
    """
    if provider not in AI_CHAT_SERVICES:
        available = ", ".join(AI_CHAT_SERVICES.keys())
        raise ValueError(f"未知的 AI 服务 Provider: {provider}，可用选项: [{available}]")

    service_class = AI_CHAT_SERVICES[provider]

    # 为 GLM 服务注入 API Key
    if provider in ("glm_free", "glm"):
        kwargs["api_key"] = api_key
        # 设置默认模型
        if "model" not in kwargs:
            from .ai_config import GLM4_FLASH_MODEL
            kwargs["model"] = GLM4_FLASH_MODEL

    return service_class(**kwargs)
